        if hm > best_a["hold"]: best_a = {"hold": hm, "graded": gm, "q0": q0, "n0": n0}
        print(f"  q0={q0:.2f} n0={n0:.1f}  graded={gm:.4f} min={gmin:.3f}  held-out={hm:.4f}{m}")

