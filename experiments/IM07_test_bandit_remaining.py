GRADED_SEEDS  = [7, 17, 27, 37, 47]
HOLDOUT_SEEDS = list(range(200_000, 200_040))
N_PULLS = 200


def score_cls(cls, seeds, kwargs=None):
    kwargs = kwargs or {}
    totals = []
    for seed in seeds:
        agent = cls(n_arms=len(STRATEGIES), **kwargs)
        env = TradingBanditEnv(total_pulls=N_PULLS)
        env.reset(seed=seed)
        total = 0.0
        for _ in range(N_PULLS):
            arm = agent.select_arm()
            r   = env.pull(arm)
            agent.update(arm, r)
            total += r
        totals.append(total)
    return np.mean(totals), np.min(totals)


# ── A. Optimistic UCB init ───────────────────────────────────────────────
class OptimisticDUCBAgent(BanditAgent):
    """D-UCB with Q_0 > 0 and N_0 > 0.

    Lecture 6 Principle 2: start above max plausible value → systematic sweep.
    With N_0 > 0, no arm is 'untried' in the raw sense; optimism drives early
    exploration instead of the fixed round-robin sweep. With discounting this
    widening effect persists because N_0 also decays, restoring the bonus.
    """

    def __init__(self, n_arms, alpha=0.15, gamma_d=0.99, c=0.01, q0=0.02, n0=1.0):
        super().__init__(n_arms)
        self.alpha   = alpha
        self.gamma_d = gamma_d
        self.c       = c
        self.values  = np.full(n_arms, q0, dtype=float)   # optimistic start
        self.n_eff   = np.full(n_arms, n0, dtype=float)   # pseudo-count
        self.raw_counts = np.zeros(n_arms, dtype=int)

    def select_arm(self):
        total = self.n_eff.sum()
        bonus = self.c * np.sqrt(np.log(total + 1.0) / self.n_eff)
        return int(np.argmax(self.values + bonus))

    def update(self, arm, reward):
        self.n_eff *= self.gamma_d
        self.values[arm] += self.alpha * (reward - self.values[arm])
        self.n_eff[arm]  += 1.0
        self.raw_counts[arm] += 1


# ── B. Phase-boundary hard reset ────────────────────────────────────────
class PhaseResetDUCBAgent(BanditAgent):
    """D-UCB with hard stat reset at pull boundaries 80 and 140.

    Agent tracks its own pull count. When a new phase starts (measured via
    IM07_arm_ev.py: bull 0-79, choppy 80-139, bear 140-199), all D-UCB stats
    are zeroed. This is the minimal change that removes inter-phase contamination
    without requiring CUSUM detection overhead.

    Lecture 4 justification: old data 'generated by a world that no longer
    exists' — forgetting is a feature. Hard reset is extreme forgetting.
    """
    PHASE_BOUNDARIES = {80, 140}

    def __init__(self, n_arms, alpha=0.15, gamma_d=0.99, c=0.01):
        super().__init__(n_arms)
        self.alpha   = alpha
        self.gamma_d = gamma_d
        self.c       = c
        self._pull_count = 0
        self._reset()

    def _reset(self):
        self.values     = np.zeros(self.n_arms)
        self.n_eff      = np.zeros(self.n_arms)
        self.raw_counts = np.zeros(self.n_arms, dtype=int)

    def select_arm(self):
        untried = np.flatnonzero(self.raw_counts == 0)
        if untried.size > 0:
            return int(untried[0])
        total = self.n_eff.sum()
        bonus = self.c * np.sqrt(np.log(total + 1.0) / self.n_eff)
        return int(np.argmax(self.values + bonus))

    def update(self, arm, reward):
        self._pull_count += 1
        if self._pull_count in self.PHASE_BOUNDARIES:
            self._reset()
        self.n_eff *= self.gamma_d
        self.values[arm] += self.alpha * (reward - self.values[arm])
        self.n_eff[arm]  += 1.0
        self.raw_counts[arm] += 1


